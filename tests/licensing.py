"""Incremental legal validation. No network, source rewrites or academic review.

REUSE lint runs on the explicitly approved scope; legacy gaps remain visible.
"""
from pathlib import Path, PurePosixPath
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from safe_paths import checked_path, project_files

SKIP = {'.git', '.quarto', '_site', 'artifacts', 'review', 'node_modules', '__pycache__',
        '.venv', '.cache', 'libros_referencia', 'clases_referencia'}


def load(root, name):
    return json.loads(checked_path(root, name).read_text())


def matches(name, patterns):
    return any(PurePosixPath(name).full_match(p) for p in patterns)


def metadata(root, policy_override=None):
    local = load(root, 'licensing.json')
    policy = policy_override or (load(root, 'tests/licensing-policy.json') if (root / 'course.yml').exists() else load(root, 'LICENSES/policy.json'))
    course = load(root, 'course.yml')['course'] if (root / 'course.yml').exists() else {}
    return local, policy, course


def annotations(root, platform_files=None, policy_override=None):
    local, policy, course = metadata(root, policy_override)
    groups = list(local['groups'])
    for entry in local.get('third_party', []):
        if entry.get('reviewed'):
            groups.append({'paths':entry['paths'], 'copyright':entry['copyright'], 'license':entry['license']})
    platform = root / 'platform-vendor.json'
    if platform_files is not None or platform.exists():
        files = platform_files if platform_files is not None else load(root, 'platform-vendor.json')['files']
        groups.append({'paths':[n for n in files if not n.startswith('LICENSES/')], 'copyright':policy['copyright'], 'license':policy['categories']['platform']})
    lines = ['# Generated by UStudyOpen; edit licensing.json or the central policy.', 'version = 1', '']
    for group in groups:
        lic = course.get('license') if group.get('category') == 'academic' else group.get('license')
        holder = course.get('authorship') if group.get('category') == 'academic' else group.get('copyright', policy['copyright'])
        lines += ['[[annotations]]', 'path = '+json.dumps(group['paths']), 'precedence = "closest"',
                  'SPDX-FileCopyrightText = '+json.dumps(holder), 'SPDX-License-Identifier = '+json.dumps(lic), '']
    return '\n'.join(lines)



def remote_urls(text):
    """Fetch-bearing HTML and Markdown resources, not ordinary citation links."""
    patterns = [r'<(?:script|img|link)\b[^>]*?\b(?:src|href)=[\'\"](https?://[^\'\"]+)',
                r'!\[[^\]]*\]\((https?://[^)\s]+)',
                r'@import\s+(?:url\()?\s*[\'\"](https?://[^\'\"]+)']
    return set().union(*(set(re.findall(p,text,re.I)) for p in patterns))


def artifact_checks(root, errors):
    local, policy, course = metadata(root)
    known = set(policy.get('remote_resources', {}))
    patterns = list(policy.get('artifact_resources', {}))
    for entry in local.get('third_party', []):
        if entry.get('reviewed'):
            known.update(entry.get('urls', []))
            patterns.extend(entry.get('artifact_paths', []))
    for path in project_files(root / '_site'):
        name = path.relative_to(root / '_site').as_posix()
        if name.startswith('site_libs/') and not matches(name, patterns):
            errors.append('unregistered incorporated artifact dependency: '+name)
        if path.suffix in {'.html','.css'}:
            for url in remote_urls(path.read_text()):
                if url not in known:
                    errors.append('unregistered remote resource; rights review required: '+url)


def validate(root, reuse=False):
    root = Path(root)
    local, policy, course = metadata(root)
    errors = []
    import legal_distribution
    legal_distribution.source_checks(root, errors)
    authorization = local.get('original_rights_authorization', {})
    if any(g.get('category') == 'academic' for g in local['groups']):
        if (authorization.get('confirmed') is not True or authorization.get('license') != course.get('license')
                or not (course.get('authorship') == authorization.get('author')
                        or course.get('authorship', '').startswith(authorization.get('author', '') + ' ('))):
            errors.append('academic rights authorization disagrees with course author/license')
    if local['policy_schema'] != policy['schema']:
        errors.append('incompatible central/local policy schema')
    template = local.get('is_template') is True and course.get('license') == 'pendiente-de-aclaracion'
    if course and not template and (not course.get('authorship') or course.get('license') is None):
        errors.append('course requires verified authorship and academic license')
    if (root / 'REUSE.toml').read_text() != annotations(root):
        errors.append('REUSE.toml stale: regenerate through central sync')
    rules = tomllib.loads(annotations(root))['annotations']
    approved = {}
    # SPDX grammar/identifiers are checked by the pinned REUSE parser, including OR/AND.
    from license_expression import get_spdx_licensing
    spdx = get_spdx_licensing()
    for rule in rules:
        if template and rule['SPDX-License-Identifier'] == 'pendiente-de-aclaracion':
            continue
        result = spdx.validate(rule['SPDX-License-Identifier'], strict=True)
        if result.errors:
            errors.append('invalid SPDX expression: '+str(result.errors))
    for entry in local.get('third_party', []):
        required = ('origin','version','license','copyright','paths','license_file','sha256')
        if not entry.get('reviewed') or any(not entry.get(k) for k in required):
            errors.append('third party requires human rights review: '+entry.get('origin','unknown'))
            continue
        if 'notice_files' not in entry:
            errors.append('third party requires explicit NOTICE review (empty list if none): '+entry['origin'])
        for notice in entry.get('notice_files', []):
            notice_path = checked_path(root, notice['path'])
            if not notice['path'].startswith('LICENSES/'):
                errors.append('NOTICE must be packaged under LICENSES/: '+notice['path'])
            if not notice_path.is_file() or hashlib.sha256(notice_path.read_bytes()).hexdigest() != notice['sha256']:
                errors.append('required upstream NOTICE missing/changed: '+notice['path'])
        path = checked_path(root, entry['license_file'])
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != entry['sha256']:
            errors.append('third-party legal text missing/changed: '+entry['license_file'])
    skips = SKIP | ({'docs'} if course else set())
    for path in project_files(root, skips, exclude_env=True):
        name = path.relative_to(root).as_posix()
        if ((course and name.startswith('_extensions/')) or name.startswith('LICENSES/')
                or '/LICENSES/' in name or name == '_extensions/ustudyopen-design/LICENSE'
                or name in {'REUSE.toml','licensing.json','design-vendor.json','platform-vendor.json'}):
            continue
        matched = [r for r in rules if matches(name, r['path'])]
        text = path.read_text(errors='ignore')
        if path.suffix in {'.qmd','.html','.css'}:
            registered = set(policy.get('remote_resources', {}))
            for entry in local.get('third_party', []):
                if entry.get('reviewed'): registered.update(entry.get('urls', []))
            for url in remote_urls(text):
                if url not in registered:
                    errors.append('unregistered remote resource; rights review required: '+url)
        if not matched and path.suffix in {'.py','.js','.mjs'} and 'UStudyOpen-Original-Authorized' in text:
            lic = re.search(r'(?m)^\s*(?:#|//)\s*SPDX-License-' r'Identifier:\s*(MIT)\s*$',text)
            holder = re.search(r'(?m)^\s*(?:#|//)\s*SPDX-FileCopyright' r'Text:\s*(.+)$',text)
            if lic and holder:
                matched = [{'path':[name], 'SPDX-License-Identifier':lic[1], 'SPDX-FileCopyrightText':holder[1]}]
                rules.append(matched[0])
        if matches(name, local.get('import_paths', [])) and not any(matches(name,e.get('paths',[])) for e in local.get('third_party',[])):
            errors.append('unregistered import requires human rights review: '+name)
            continue
        if matched:
            rule = matched[-1]
            if template and rule['SPDX-License-Identifier'] == 'pendiente-de-aclaracion':
                continue
            text = path.read_text(errors='ignore')
            declared = re.findall(r'(?m)^\s*(?:#|//|/\*|\*)?\s*SPDX-License-' r'Identifier:\s*([^\r\n]+)', text)
            if any(x.strip(' */#') != rule['SPDX-License-Identifier'] for x in declared):
                errors.append('contradictory SPDX license: '+name)
            # SPDX notices and explicit copyright must not silently be overridden by a group.
            holders = re.findall(r'(?m)^\s*(?:#|//|/\*|\*)?\s*SPDX-FileCopyright' r'Text:\s*([^\r\n]+)', text)
            conventional = re.findall(r'(?im)^\s*(?:#|//|/\*|\*)?\s*Copyright(?:\s*\(c\)|\s*©)?\s+(\d{4}[^\r\n]+)',text)
            if conventional and any(rule['SPDX-FileCopyrightText'] not in x for x in conventional):
                errors.append('contradictory copyright requires human review: '+name)
            if holders and any(x.strip(' */#') != rule['SPDX-FileCopyrightText'] for x in holders):
                errors.append('contradictory copyright: '+name)
            if name != 'LICENSE':
                approved[name] = path
        elif name not in local.get('legacy_review', {}):
            errors.append('unclassified new resource; declare original rights or third-party origin: '+name)
        elif hashlib.sha256(path.read_bytes()).hexdigest() != local['legacy_review'][name]['sha256']:
            errors.append('legacy resource changed; provenance review required: '+name)
    for manifest, prefix in [('design-vendor.json','_extensions/ustudyopen-design/'),('platform-vendor.json','')]:
        if not (root / manifest).exists():
            continue
        manifest_files = load(root, manifest)['files']
        if prefix:
            actual = {p.relative_to(root / prefix).as_posix() for p in project_files(root / prefix)}
            if actual != set(manifest_files):
                errors.append('unlisted or missing extension files')
        for name, sha in manifest_files.items():
            path = checked_path(root, prefix+name)
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != sha:
                errors.append('vendor integrity mismatch: '+prefix+name)
    if reuse:
        with tempfile.TemporaryDirectory(prefix='uso-reuse-') as temp:
            stage = Path(temp)
            (stage / 'REUSE.toml').write_text(annotations(root))
            for name, path in approved.items():
                out = checked_path(stage, name)
                out.parent.mkdir(parents=True,exist_ok=True)
                shutil.copy2(path,out)
            shutil.copytree(root / 'LICENSES', stage / 'LICENSES')
            used = set()
            for name in approved:
                rule = [r for r in rules if matches(name,r['path'])][-1]
                used.update(re.findall(r'[A-Za-z0-9.+-]+', rule['SPDX-License-Identifier']))
            # Exact third-party historical texts stay distributed; lint only uses SPDX-named legal codes.
            for p in (stage / 'LICENSES').iterdir():
                if p.suffix != '.txt' or p.stem not in used:
                    if p.is_file(): p.unlink()
            result = subprocess.run([sys.executable,'-m','reuse','--root',str(stage),'lint'],capture_output=True,text=True)
            if result.returncode:
                errors.append('REUSE approved scope: '+result.stdout+result.stderr)
    return errors


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--reuse',action='store_true')
    args = parser.parse_args()
    try:
        errors = validate(args.root,args.reuse)
    except (OSError,ValueError,KeyError,TypeError) as error:
        errors = [str(error)]
    print(json.dumps({'errors':errors,'scope':'incremental; legacy_review is not REUSE compliance'},ensure_ascii=False,indent=2))
    raise SystemExit(bool(errors))

if __name__ == '__main__':
    main()
